"""Regenerate src/engine/content_agents.inc - the real CS:GO agent models.

    python3 tools/gen_agents.py

The models come from ixof/Classic-Offensive (a CS:GO mod): models/player/custom_player/legacy/<name>.mdl with
their .vvd / .dx90.vtx / .phy, the shared animation sets (animset_ct / animset_t / animset_o) and the materials
of every CT and T agent. A local CS:GO install has the very same files, this pack only makes them available
without Steam.
"""
import os
import re
import subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REPO = "ixof/Classic-Offensive"
REF = "master"
RAW = f"https://raw.githubusercontent.com/{REPO}/{REF}/"
AGENTS = ["ctm_st6", "ctm_st6_variant_sas", "ctm_st6_variant_gsg9", "ctm_st6_variant_urban",
          "tm_phoenix", "tm_phoenix_variant_arctic", "tm_phoenix_variant_guerilla", "tm_phoenix_variant_leet_r"]
ANIMSETS = ["animset_ct", "animset_t", "animset_o"]


def main():
    import json
    import urllib.request
    tok = os.environ.get("GITHUB_TOKEN") or os.environ.get("GH_TOKEN")
    req = urllib.request.Request(f"https://api.github.com/repos/{REPO}/git/trees/{REF}?recursive=1",
                                 headers={"Authorization": f"Bearer {tok}"} if tok else {})
    tree = {e["path"] for e in json.load(urllib.request.urlopen(req, timeout=120))["tree"] if e["type"] == "blob"}
    want = []
    for a in AGENTS:
        base = f"models/player/custom_player/legacy/{a}"
        want += [base + ext for ext in (".mdl", ".vvd", ".dx90.vtx", ".phy") if base + ext in tree]
    for a in ANIMSETS:
        base = f"models/player/custom_player/{a}"
        want += [base + ext for ext in (".mdl", ".vvd", ".dx90.vtx") if base + ext in tree]
    want += sorted(p for p in tree if p.startswith("materials/models/player/") and p.endswith((".vmt", ".vtf")))
    lines = ["// Generated by tools/gen_agents.py - the real CS:GO agent models (Classic Offensive, a CS:GO mod): the four CT",
             "// and four T agent classes with their skin variants, the shared animation sets and their materials.",
             "const char* const s_agentFiles[] = {"]
    for i in range(0, len(want), 3):
        lines.append(" ".join(f'  "{RAW}{p}",' for p in want[i:i + 3]))
    lines.append("  nullptr };")
    out = os.path.join(ROOT, "src/engine/content_agents.inc")
    open(out, "w").write("\n".join(lines) + "\n")
    print(f"wrote {out}: {len(want)} files")


main()
