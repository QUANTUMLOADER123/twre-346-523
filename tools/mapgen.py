#!/usr/bin/env python3
"""Map layout generator for Counter-Strike: HvH.

Draws map layouts with rectangle operations and writes assets/maps/<name>.map
(see src/game/shared/mapinfo.cpp for the format). Layouts are inspired by classic
Counter-Strike maps (not copies): 1 cell = 64 units.

usage: python3 tools/mapgen.py [--png]   (--png writes a preview image next to each map, needs no deps)
"""
import os, sys, zlib, struct

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
OUT = os.path.join(ROOT, 'assets', 'maps')


class Canvas:
    def __init__(self, w, h, fill='#'):
        self.w, self.h = w, h
        self.g = [[fill] * w for _ in range(h)]
        self.header = []
        self.places = []
        self.lights = []

    def fill(self, x0, y0, x1, y1, ch):
        for y in range(min(y0, y1), max(y0, y1) + 1):
            for x in range(min(x0, x1), max(x0, x1) + 1):
                if 0 <= x < self.w and 0 <= y < self.h:
                    self.g[y][x] = ch

    def put(self, x, y, ch):
        if 0 <= x < self.w and 0 <= y < self.h:
            self.g[y][x] = ch

    def place(self, name, x0, y0, x1, y1):
        self.places.append((name, x0, y0, x1, y1))

    def get(self, x, y):
        return self.g[y][x] if 0 <= x < self.w and 0 <= y < self.h else '#'

    def vary_walls(self, alt='%', near='tL', base='#'):
        """use the alternate wall material next to given floor chars (tunnels look different)"""
        for y in range(self.h):
            for x in range(self.w):
                if self.g[y][x] != base:
                    continue
                for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                    if self.get(x + dx, y + dy) in near:
                        self.g[y][x] = alt
                        break

    def write(self, name):
        os.makedirs(OUT, exist_ok=True)
        path = os.path.join(OUT, name + '.map')
        with open(path, 'w', newline='\n') as f:
            f.write('// generated by tools/mapgen.py - edit there or by hand\n')
            for line in self.header:
                f.write(line + '\n')
            for p in self.places:
                f.write('place "%s" %d %d %d %d\n' % p)
            for l in self.lights:
                f.write('light ' + ' '.join(str(v) for v in l) + '\n')
            f.write('grid\n')
            for row in self.g:
                f.write(''.join(row).rstrip() + '\n')
            f.write('end\n')
        print('wrote', path, '%dx%d' % (self.w, self.h))
        if '--png' in sys.argv:
            self.png(path.replace('.map', '_layout.png'))

    def png(self, path, s=6):
        pal = {'#': (90, 70, 50), '%': (110, 85, 60), '&': (200, 200, 190), '@': (60, 55, 50), 't': (150, 120, 80), 'L': (230, 200, 80),
               'T': (230, 80, 50), 'K': (60, 110, 230), 'A': (240, 60, 60), 'B': (240, 60, 60), 'c': (160, 110, 50), 'C': (120, 80, 40),
               'b': (60, 90, 150), 'w': (140, 130, 110), 'W': (120, 110, 90), '>': (210, 210, 120), '<': (210, 210, 120), '^': (210, 210, 120),
               'v': (210, 210, 120), ' ': (0, 0, 0)}
        rows = []
        for y in range(self.h):
            r = bytearray([0])
            for x in range(self.w):
                ch = self.g[y][x]
                if ch in pal:
                    c = pal[ch]
                elif ch.isdigit():
                    k = 170 + int(ch) * 9
                    c = (k, k - 10, k - 40)
                else:
                    c = (200, 180, 140)
                r += bytes(c) * s
            for _ in range(s):
                rows.append(bytes(r))
        raw = b''.join(rows)
        def chunk(t, d):
            return struct.pack('>I', len(d)) + t + d + struct.pack('>I', zlib.crc32(t + d) & 0xffffffff)
        with open(path, 'wb') as f:
            f.write(b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', self.w * s, self.h * s, 8, 2, 0, 0, 0)) +
                    chunk(b'IDAT', zlib.compress(raw, 9)) + chunk(b'IEND', b''))


